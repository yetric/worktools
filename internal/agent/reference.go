// Package agent prepares project command references without executing project commands.
package agent

import (
	"errors"
	"fmt"
	"html"
	"os"
	"path/filepath"
	"strings"
	"unicode"

	"github.com/BurntSushi/toml"
	"github.com/yetric/worktools/internal/catalog"
	"github.com/yetric/worktools/internal/dev"
	"github.com/yetric/worktools/internal/pod"
)

const Start = "<!-- worktools:commands:start -->"
const End = "<!-- worktools:commands:end -->"
const LegacyStart = "<!-- dotfiles-aliases:start -->"
const LegacyEnd = "<!-- dotfiles-aliases:end -->"
const SelectionFile = ".worktools/agent.toml"

type Selection struct {
	Version int      `toml:"version" json:"version"`
	Tools   []string `toml:"tools" json:"tools"`
	Files   []string `toml:"files" json:"files"`
}

func Defaults() Selection {
	selection := Selection{Version: 1, Files: []string{"AGENTS.md", "CLAUDE.md"}}
	for _, tool := range catalog.Selectable() {
		selection.Tools = append(selection.Tools, tool.Name)
	}
	return selection
}

func Normalize(selection Selection) (Selection, error) {
	if selection.Version != 1 {
		return selection, fmt.Errorf("unsupported agent selection version %d", selection.Version)
	}
	canonical := Defaults()
	normalize := func(values, allowed []string, label string) ([]string, error) {
		seen := map[string]bool{}
		for _, value := range values {
			valid := false
			for _, name := range allowed {
				valid = valid || value == name
			}
			if !valid {
				return nil, fmt.Errorf("unknown %s %q", label, value)
			}
			seen[value] = true
		}
		if len(seen) == 0 {
			return nil, fmt.Errorf("select at least one %s", label)
		}
		result := []string{}
		for _, name := range allowed {
			if seen[name] {
				result = append(result, name)
			}
		}
		return result, nil
	}
	var e error
	selection.Tools, e = normalize(selection.Tools, canonical.Tools, "tool")
	if e != nil {
		return selection, e
	}
	selection.Files, e = normalize(selection.Files, canonical.Files, "instruction file")
	return selection, e
}

func Render(directory string, selection Selection) (string, error) {
	var out strings.Builder
	out.WriteString(Start + "\n## Worktools commands\n\n")
	out.WriteString("Generated by `worktools agent`. Project instructions and required checks take precedence.\n")
	out.WriteString("These are standalone CLIs; ensure the Worktools install directory (normally `~/.local/bin`) is on PATH.\n")
	out.WriteString("Use explicit actions in automation, `--help` for options, and inspection before execution.\n")
	out.WriteString("Only run operations authorized by the task. This reference does not grant permission to install tools, change services, modify databases, or publish changes.\n\n")
	for _, name := range selection.Tools {
		tool, _ := catalog.Get(name)
		fmt.Fprintf(&out, "### %s — %s\n\n| Command | Purpose |\n| --- | --- |\n", tool.Name, tool.Description)
		for _, command := range tool.Commands {
			fmt.Fprintf(&out, "| %s | %s |\n", code(command.Usage), cell(command.Description))
		}
		out.WriteString("\n")
		for _, note := range tool.Notes {
			out.WriteString(note + "\n\n")
		}
		if name == "dev" {
			root, e := dev.Root(directory, dev.Builtins())
			if e != nil && !errors.Is(e, dev.ErrNoProject) {
				return "", e
			}
			if e == nil {
				records, e := dev.Discover(root, dev.Builtins())
				if e != nil {
					return "", e
				}
				if len(records) > 0 {
					out.WriteString("Detected project actions (a snapshot; recheck with `dev list --json`):\n\n| Action | Resolution | Description |\n| --- | --- | --- |\n")
					for _, record := range records {
						fmt.Fprintf(&out, "| %s | %s | %s |\n", code("dev "+record.Name), cell(record.Status), cell(record.Description))
					}
					out.WriteString("\n")
				}
				var config struct {
					Dev struct {
						Runner string `toml:"runner"`
					} `toml:"dev"`
				}
				path := filepath.Join(root, ".worktools.toml")
				if _, e := os.Stat(path); e == nil {
					if _, e := toml.DecodeFile(path, &config); e != nil {
						return "", e
					}
					if config.Dev.Runner != "" {
						fmt.Fprintf(&out, "Project runner preference: %s, from `.worktools.toml`. Explicit action mappings take precedence.\n\n", code(config.Dev.Runner))
					}
				}
			} else {
				out.WriteString("No supported development manifest was found. Add explicit `.worktools.toml` actions for custom tooling.\n\n")
			}
		}
		if name == "pod" {
			config, e := pod.LoadConfig(directory)
			if e != nil {
				return "", e
			}
			if config.Provider != "" {
				fmt.Fprintf(&out, "Project provider preference: %s, from `.worktools.toml`. Explicit flags and environment preferences take precedence.\n\n", code(config.Provider))
			}
		}
	}
	out.WriteString("Refresh this reference with `worktools agent preview`, then `worktools agent sync`.\n" + End + "\n")
	return out.String(), nil
}

func cell(value string) string {
	value = strings.Map(func(r rune) rune {
		if unicode.IsControl(r) {
			return ' '
		}
		return r
	}, value)
	value = strings.Join(strings.Fields(value), " ")
	return strings.ReplaceAll(strings.ReplaceAll(html.EscapeString(value), "|", "&#124;"), "`", "&#96;")
}
func code(value string) string { return "<code>" + cell(value) + "</code>" }

// Replace owns only the delimited section. Bytes outside it remain untouched.
func Replace(original, block string, remove bool) (string, bool, error) {
	start, end := Start, End
	modern := strings.Contains(original, Start) || strings.Contains(original, End)
	legacy := strings.Contains(original, LegacyStart) || strings.Contains(original, LegacyEnd)
	if modern && legacy {
		return "", false, errors.New("both Worktools and legacy markers found; resolve the duplicate managed sections first")
	}
	if legacy {
		start, end = LegacyStart, LegacyEnd
	}
	if modern || legacy {
		if strings.Count(original, start) != 1 || strings.Count(original, end) != 1 {
			return "", false, errors.New("expected exactly one pair of managed reference markers")
		}
		a, b := strings.Index(original, start), strings.Index(original, end)
		if a >= b {
			return "", false, errors.New("managed reference markers are out of order")
		}
		// Markers must be whole lines, rather than examples embedded in prose.
		lineBoundary := func(pos int) bool { return pos == 0 || original[pos-1] == '\n' }
		if !lineBoundary(a) || !lineBoundary(b) {
			return "", false, errors.New("managed reference markers must be on their own lines")
		}
		for _, pos := range []int{a + len(start), b + len(end)} {
			if pos < len(original) && original[pos] != '\n' && !(original[pos] == '\r' && pos+1 < len(original) && original[pos+1] == '\n') {
				return "", false, errors.New("managed reference markers must be on their own lines")
			}
		}
		if remove {
			return original[:a] + original[b+len(end):], legacy, nil
		}
		block = strings.TrimSuffix(block, "\n")
		if strings.Contains(original, "\r\n") {
			block = strings.ReplaceAll(block, "\n", "\r\n")
		}
		return original[:a] + block + original[b+len(end):], legacy, nil
	}
	if remove {
		return original, false, nil
	}
	newline := "\n"
	if strings.Contains(original, "\r\n") {
		newline = "\r\n"
		block = strings.ReplaceAll(block, "\n", newline)
	}
	separator := ""
	if original != "" {
		separator = newline
		if !strings.HasSuffix(original, "\n") {
			separator += newline
		}
	}
	return original + separator + block, false, nil
}
